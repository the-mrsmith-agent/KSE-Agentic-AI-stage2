"""A plain-language briefing on Ukraine's air-raid alerts and how well forecasts did.

Reads only files the pipeline already wrote — no network, no fitting, no wall-clock:

    data/raw/alerts_snapshot.csv   the alert history            (via src.features.load_alerts)
    reports/predictions.csv        day-ahead holdout guesses   (dumped by src.evaluate)
    reports/metrics.json           holdout scores              (src.evaluate)

    python -m src.brief    ->  prints the brief and writes reports/brief.md

The output avoids statistics vocabulary on purpose and carries plain units ("alerts a day",
"minutes off", "times in 100"), so a non-technical reader gets something useful. `brief.md`
and the terminal always show the same text; every number is derived from the artifacts above.

ponytail: prose templates + rounded numbers + three embedded figures taken from
`reports/figures/` (generated by eda/evaluate, not here); upgrade path: more figures if
readers ask.
"""

from __future__ import annotations

import json
import pathlib

import pandas as pd

from src.features import load_alerts

METRICS = pathlib.Path("reports/metrics.json")
PREDICTIONS = pathlib.Path("reports/predictions.csv")
OUT = pathlib.Path("reports/brief.md")
FIGDIR = pathlib.Path("reports/figures")

KYIV = "Europe/Kyiv"
DOW = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


def _load(path: pathlib.Path, parse):
    return parse(path) if path.exists() else None


def _fig(name: str, caption: str) -> list[str]:
    """Embed a generated figure in the Markdown, or nothing if it is not on disk yet.

    Keeps `python -m src.brief` runnable on its own, before `eda`/`evaluate` have made the
    figures. In the terminal the same line just names the file (images cannot render there).
    """
    return [f"![{caption}](figures/{name})", ""] if (FIGDIR / name).exists() else []


def _duration(minutes: float) -> str:
    return f"{round(minutes)} minutes" if minutes < 90 else f"{minutes / 60:.1f} hours"


def _year_rate(alerts: pd.DataFrame, local: pd.Series, year: int) -> float:
    """Alert starts per day inside `year`, over the days of that year the data covers."""
    lo = max(local.min().normalize(), pd.Timestamp(f"{year}-01-01", tz=KYIV))
    hi = min(local.max().normalize(), pd.Timestamp(f"{year}-12-31", tz=KYIV))
    days = (hi - lo).days + 1
    return int((local.dt.year == year).sum()) / days


def _busiest_week_hour(local: pd.Series) -> tuple[str, str]:
    """Most / least likely weekday+hour to see an alert start, per weekday-hour slot.

    Counts are divided by how often that weekday occurs in the window, otherwise a partial
    final week would make some slots look artificially quiet.
    """
    counts = pd.DataFrame({"dow": local.dt.dayofweek, "hour": local.dt.hour}).value_counts()
    wd_days = local.dt.normalize().drop_duplicates().dt.dayofweek.value_counts()
    rate = counts / wd_days.reindex(counts.index.get_level_values("dow")).to_numpy()

    def label(key) -> str:
        dow, hour = key
        return f"{DOW[dow]} around {hour:02d}:00"

    return label(rate.idxmax()), label(rate.idxmin())


def _counts_lines(metrics: dict) -> list[str]:
    counts = metrics["counts_daily"]["y_starts_day"]
    model, simple = counts["histgb"], counts["seasonal_naive"]
    return [
        "**How many alerts to expect — the forecast genuinely helps.**",
        f"- Off by about **{model['mae']:.1f} alerts** per region per day; the simple "
        f"\"assume a typical recent day\" guess is off by {simple['mae']:.1f}.",
        f"- Countrywide: about **{model['national_mae']:.0f} alerts a day** wrong, against "
        f"about {simple['national_mae']:.0f} for the simple guess.",
    ]


def _counts_table(preds: pd.DataFrame) -> list[str]:
    day = pd.to_datetime(preds["origin"], utc=True).dt.tz_convert(KYIV).dt.strftime("%a %d %b")
    national = preds.assign(day=day).groupby("day", sort=False)[
        ["y_starts_day", "p_histgb_start", "p_snaive_start"]
    ].sum()
    rows = ["", "| Day | Sirens that really started | Model guessed | Simple guess |", "|---|---|---|---|"]
    rows += [
        f"| {d} | {r['y_starts_day']:.0f} | {r['p_histgb_start']:.0f} | {r['p_snaive_start']:.0f} |"
        for d, r in national.iterrows()
    ]
    return rows


def _region_table(preds: pd.DataFrame, top: int = 8) -> list[str]:
    per_region = preds.groupby("region")[["y_minutes_day", "p_histgb_min"]].mean() / 60
    per_region = per_region.sort_values("y_minutes_day", ascending=False).head(top)
    rows = ["", "| Region | Hours under sirens per day (real) | Model guessed |", "|---|---|---|"]
    rows += [
        f"| {region} | {r['y_minutes_day']:.1f} | {r['p_histgb_min']:.1f} |"
        for region, r in per_region.iterrows()
    ]
    return rows


def _window_line(metrics: dict) -> str:
    start, end = metrics["splits"]["test"][0], metrics["splits"]["test"][1]
    def day(ts):
        return pd.Timestamp(ts).tz_convert(KYIV).strftime("%d %b %Y")
    return f"{day(start)} → {day(end)}"


def _forecast_section(metrics: dict, preds: pd.DataFrame) -> list[str]:
    events = metrics["start_events"]["histgb"]["tol_30"]
    simple = metrics["start_events"]["seasonal_naive"]["tol_30"]
    duration = metrics["duration"]["histgb_q50"]
    duration_simple = metrics["duration"]["duration_naive"]

    return [
        "## What we tried to predict, and how it went",
        "",
        f"Test: the last 14 days of data ({_window_line(metrics)}). One forecast per region per "
        "day, each made the evening before, then checked against what really happened. The "
        "forecast never saw these days while learning.",
        "",
        *_counts_lines(metrics),
        *_counts_table(preds),
        "",
        *_fig("eval_national_daily.png", "Last 14 days: what really happened vs the model's guess vs the simple guess"),
        "**Which hour an alert starts — about half right.**",
        f"- Of the hours flagged as risky, about **{events['precision'] * 10:.0f} in 10** really "
        f"had an alert; it named the right hour for about {events['recall'] * 10:.0f} in 10 of the "
        f"alerts that really happened. The simple guesses manage about "
        f"{simple['precision'] * 10:.0f} in 10 either way.",
        "- The exact minute is not predictable — nobody got close on that.",
        "",
        "**How long an alert lasts — essentially unsolved.**",
        f"- Length guesses are off by about **{duration['mae_minutes']:.0f} minutes** on average; "
        f"always answering \"the usual length\" is off by {duration_simple['mae_minutes']:.0f} "
        "minutes. The \"between X and Y minutes\" range held up about "
        f"{duration['coverage'] * 100:.0f} times in 100.",
        "",
        f"**Where the burden falls in the test period** (the 8 busiest regions by siren time):",
        *_region_table(preds),
        "",
    ]


def build(alerts: pd.DataFrame, metrics: dict | None, preds: pd.DataFrame | None) -> str:
    local = alerts["started_at"].dt.tz_convert(KYIV)
    first, last = local.min().strftime("%d %b %Y"), local.max().strftime("%d %b %Y")
    days = (local.max().normalize() - local.min().normalize()).days + 1

    durations = alerts["duration_min"].dropna()
    median_d, p90_d = durations.quantile([0.5, 0.9])
    night = float((local.dt.hour.isin([22, 23, 0, 1, 2, 3, 4, 5])).mean())
    gaps = alerts.groupby("region")["started_at"].diff().dt.total_seconds().div(3600).dropna()
    peak, quiet = _busiest_week_hour(local)
    hours = (alerts.groupby("region")["duration_min"].sum() / days / 60).sort_values(ascending=False)

    rate_2026, rate_2022 = _year_rate(alerts, local, 2026), _year_rate(alerts, local, 2022)
    # A window starting after 2022 (or a stub fixture) would make the 2022 rate 0; then the
    # volume line just states the current rate instead of dividing by it.
    volume = f"{rate_2026:.0f} siren starts a day across the country"
    if rate_2022 > 0:
        volume += f"; in 2022 it was {rate_2022:.0f} — **{rate_2026 / rate_2022:.1f}× more**"
    busiest = ", ".join(f"{r} ~{h:.1f} h" for r, h in hours.head(3).items())
    quietest = ", ".join(f"{r} ~{h:.1f} h" for r, h in hours.tail(3).items())

    lines = [
        "# Air-raid alerts in Ukraine — the short version",
        "",
        f"{len(alerts):,} air-raid alerts across {alerts['region'].nunique()} regions of Ukraine, "
        f"{first} → {last}. All times are Kyiv time.",
        "",
        "## Life under sirens",
        f"- 2026 brings about {volume}. Most of the rise is recent: the daily average climbed "
        "again in late August 2026.",
        f"- Half of all alerts are over within {_duration(median_d)}; 9 in 10 within "
        f"{_duration(p90_d)}.",
        f"- Alerts come in waves: in a region, the next siren usually starts within "
        f"{gaps.median():.1f} h of the previous one.",
        f"- About {night * 10:.0f} in 10 alerts start at night (22:00–06:00).",
        "",
        *_fig("daily_starts.png", "Alert starts per day since Feb 2022 — the level keeps rising"),
        "## When, and where, they happen",
        f"- Busiest slot of the week: **{peak}**. Quietest: {quiet}.",
        f"- Most siren time per day on average since 2022: {busiest}.",
        f"- Least: {quietest}.",
        "",
        *_fig("hour_of_week_heatmap.png", "Alert starts by weekday and hour, Kyiv time — Monday noon is the busiest slot"),
    ]

    if metrics is not None and preds is not None:
        lines += _forecast_section(metrics, preds)
    else:
        lines += [
            "## What we tried to predict, and how it went",
            "",
            "The forecast-vs-reality part needs `reports/predictions.csv` and "
            "`reports/metrics.json`: run `python -m src.evaluate` first.",
            "",
        ]

    lines += [
        "## What this is not",
        "- Not an early-warning system. It says a day and a region look busy; it cannot say "
        "\"sirens at 14:03 in your street\".",
        "- Oblast-wide only — no city, no district.",
        "- Volunteer-collected data: some alerts are missing, and Luhansk and Crimea are absent "
        "(their sirens are effectively permanent).",
        "",
        "Technical version, with the full scoring rules and how we stopped the forecast "
        "peeking at the future: `reports/findings.md`. Figures: `reports/figures/`.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    text = build(load_alerts(), _load(METRICS, lambda p: json.loads(p.read_text())), _load(PREDICTIONS, pd.read_csv))
    print(text, end="")  # same bytes as brief.md, no extra trailing newline on the terminal
    OUT.write_text(text)


if __name__ == "__main__":
    main()
